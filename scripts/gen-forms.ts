import fs from "node:fs";
import { FORM_FIELDS, FormName } from "../src/lib/formFields";

export function buildFormsHtml(): string {
  const forms = (Object.keys(FORM_FIELDS) as FormName[]).map((name) => {
    const { text, files } = FORM_FIELDS[name];
    const enctype = files.length ? ' enctype="multipart/form-data"' : "";
    const inputs = [
      `<input type="hidden" name="form-name" value="${name}" />`,
      `<input name="bot-field" />`,
      ...text.map((f) => `<input name="${f}" />`),
      ...files.map((f) => `<input type="file" name="${f}" />`),
    ];
    return `    <form name="${name}" data-netlify="true" netlify-honeypot="bot-field"${enctype} hidden>\n      ${inputs.join("\n      ")}\n    </form>`;
  });
  return `<!DOCTYPE html>
<html lang="en">
  <head><meta charset="utf-8" /><title>Form definitions (Netlify detection only)</title></head>
  <body>
    <!-- GENERATED by scripts/gen-forms.ts from src/lib/formFields.ts — do not edit by hand. -->
${forms.join("\n")}
  </body>
</html>
`;
}

if (process.argv[1]?.endsWith("gen-forms.ts")) {
  fs.writeFileSync("public/__forms.html", buildFormsHtml());
  console.log("gen-forms: public/__forms.html written");
}
